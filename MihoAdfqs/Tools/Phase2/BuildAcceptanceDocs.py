#职责：提取一个章节中的非空段落，并保存原始起始行号。
def blocks(lines, start, end):
    current = []
    first = start
    for number in range(start, min(end, len(lines)) + 1):
        text = lines[number - 1].strip()
        if text:
            if not current:
                first = number
            current.append(text)
        elif current:
            yield first, current
            current = []
    if current:
        yield first, current


#职责：应用用户确认的原文笔误解释，并将背景章节转换为机制验收。
def mechanics(number, rows):
    if number == '06' and rows[0] == '超新星轨道空降部队盔甲':
        rows = ['覆盖范围：全身（用户确认）' if row == '覆盖范围：头部' else
                '穿戴槽：外层护甲，可与同系列头盔同时穿戴（用户确认）' if row == '穿戴槽：头部' else row for row in rows]
    if number == '12':
        rows = ['完成后元首支援技能仍召唤4名亲卫，只取消队长召唤（用户确认）'
                if '同时元首的支援技能' in row else row for row in rows]
    if number != '03':
        return [row for row in rows if not row.startswith('描述：')]
    if len(rows) < 3:
        return rows
    return [rows[0]] + [row for row in rows[1:] if re.match(
        r'^(智识|格斗|射击|社交|手工|种植|烹饪|全部属性|其余全部属性|特殊效果)', row)]


#职责：为章节生成可勾选的逐段需求与人工结果记录栏。
def write_module(lines, item):
    number, title, start, end, procedure, status = item
    text = [f'# 二期测试 {number}：{title}', '',
            f'原始需求：[二期.txt](../二期.txt) 第 {start}—{min(end, len(lines))} 行。', '',
            f'当前实现状态：{status}', '',
            '以下内容是需求预期，不是测试通过报告。所有结果默认未测；标为未接入的功能应先登记“未完成”，后续实现后再测。', '',
            '## 操作步骤', '', procedure, '',
            '逐个完成下面的用例。数值以需求原文为准；游戏显示受到材料、品质、基因、背景和装备影响时，记录参与计算的所有来源。描述文字在信息页对照相应原文，机制结果在下列清单记录。', '']
    case = 0
    for first, rows in blocks(lines, start, end):
        rows = mechanics(number, rows)
        if not rows:
            continue
        case += 1
        heading = rows[0]
        if len(heading) > 55:
            heading = heading[:55] + '…'
        text += [f'## P2-{number}-{case:03d} {heading}', '', f'原文定位：第 {first} 行起。', '']
        for row in rows:
            text.append(f'- [ ] {row}')
        text += ['', '结果：□未测 □通过 □失败 □未完成　实际现象／日志：________', '']
    (OUTPUT / f'{number}-{title}.md').write_text('\n'.join(text), encoding='utf-8')
    return case


